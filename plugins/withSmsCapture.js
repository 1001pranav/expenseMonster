/**
 * Bank SMS import on request (only in builds made with EXPO_PUBLIC_SMS_CAPTURE=1; see app.config.ts).
 *
 * Nothing listens for incoming SMS: there is no receiver and no RECEIVE_SMS. The inbox is read only
 * when the user taps "Import bank SMS" (Settings → Bank SMS), which starts SmsImportActivity (no UI).
 * It reads messages newer than the time the app passes in and keeps only those from business sender
 * IDs (Indian DLT "VM-HDFCBK", "AD-SBIUPI-S"), or senders the user marked as a bank (the app passes
 * them as "allow": a co-op bank texting from a phone number), that mention an amount and a payment
 * word and are not OTPs. Kept messages go to files/sms-inbox/ in the app's private storage;
 * the app (src/services/smsInbox.ts) parses them and deletes each file straight away. Nothing is sent
 * anywhere. Other apps can't start the import: it needs a signature permission only this app holds.
 *
 * Google Play allows READ_SMS only for default SMS apps or declared exceptions, so this is meant for
 * the sideloaded APK until a declaration is approved. Generates at prebuild (never edit android/).
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const inboxKt = (pkg) => `// Generated by plugins/withSmsCapture.js
package ${pkg}

import android.content.Context
import org.json.JSONObject
import java.io.File

/** Copies bank and payment transaction SMS (never OTPs or personal messages) to an app-private folder. */
object SmsInbox {
  // Business sender IDs: "VM-HDFCBK", "AD-SBIUPI-S", or shown bare ("HDFCBK"). Needs a letter, so phone numbers never match.
  private val SENDER = Regex("^([A-Z]{2}-)?(?=[A-Z0-9]*[A-Z])[A-Z0-9]{4,9}(-[A-Z])?$", RegexOption.IGNORE_CASE)
  private val MONEY = Regex("(rs\\\\.?|inr|\\u20B9)\\\\s?[0-9]", RegexOption.IGNORE_CASE)
  private val PAYMENT = Regex("debit|credit|spent|withdrawn|paid|sent|received|txn|transaction|a/c|acct|card|upi|refund|statement|due", RegexOption.IGNORE_CASE)
  private val OTP = Regex("(otp|one[ -]?time password|verification code)\\\\s*(is|:|for)|is (your|the) (otp|one[ -]?time password|verification code)", RegexOption.IGNORE_CASE)

  fun dir(context: Context): File = File(context.filesDir, "sms-inbox")

  /** Same as normalizeSender in src/domain/smsSender.ts: last 10 digits of a number, else the bare DLT id. */
  fun normalize(sender: String): String {
    val s = sender.trim().uppercase()
    if (Regex("^[+0-9][0-9\\\\s()-]{5,}$").matches(s)) return s.replace(Regex("[^0-9]"), "").takeLast(10)
    return s.replace(Regex("^[A-Z]{2}-(?=[A-Z0-9]{4})"), "").replace(Regex("-[A-Z]$"), "").replace(Regex("[^A-Z0-9]"), "")
  }

  fun wanted(sender: String, body: String, allow: Set<String>): Boolean =
    (SENDER.matches(sender.trim()) || normalize(sender) in allow) && MONEY.containsMatchIn(body) && PAYMENT.containsMatchIn(body) && !OTP.containsMatchIn(body)

  fun offer(context: Context, sender: String, body: String, at: Long, allow: Set<String>) {
    if (!wanted(sender, body, allow)) return
    val folder = dir(context)
    folder.mkdirs()
    val json = JSONObject()
    json.put("sender", sender.trim())
    json.put("body", body)
    json.put("at", at)
    val name = String.format("%013d-%08x.json", at, (sender + body).hashCode())
    File(folder, name).writeText(json.toString())
  }
}
`;

const importKt = (pkg) => `// Generated by plugins/withSmsCapture.js
package ${pkg}

import android.Manifest
import android.app.Activity
import android.content.pm.PackageManager
import android.os.Bundle
import android.provider.Telephony
import java.io.File

/**
 * No UI: copies bank SMS received after "since" (ms) into the app's inbox folder, writes
 * "<token>.done" so the app knows it finished, then closes. Runs only when the user asks.
 */
class SmsImportActivity : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    @Suppress("DEPRECATION")
    val since = (intent.extras?.get("since") as? Number)?.toLong() ?: (System.currentTimeMillis() - 90 * 86_400_000L)
    val token = intent.getStringExtra("token")?.takeIf { Regex("^[A-Za-z0-9-]{1,64}$").matches(it) } ?: "import"
    // Senders the user marked as a bank, already normalised: "9876543210,MYCOOP".
    val allow = (intent.getStringExtra("allow") ?: "").split(",").map { it.trim() }.filter { it.isNotEmpty() }.toSet()
    val app = applicationContext
    val done = { SmsInbox.dir(app).mkdirs(); File(SmsInbox.dir(app), "$token.done").writeText("") }
    if (checkSelfPermission(Manifest.permission.READ_SMS) != PackageManager.PERMISSION_GRANTED) {
      done()
      finish()
      return
    }
    Thread {
      try {
        val columns = arrayOf(Telephony.Sms.ADDRESS, Telephony.Sms.BODY, Telephony.Sms.DATE)
        app.contentResolver.query(Telephony.Sms.Inbox.CONTENT_URI, columns, Telephony.Sms.DATE + " > ?", arrayOf(since.toString()), Telephony.Sms.DATE + " ASC")?.use { c ->
          while (c.moveToNext()) {
            val sender = c.getString(0)
            val body = c.getString(1)
            if (sender != null && body != null) SmsInbox.offer(app, sender, body, c.getLong(2), allow)
          }
        }
      } catch (e: Exception) {
        // Nothing imported; the app shows "No new bank SMS found".
      }
      try { done() } catch (e: Exception) {}
      runOnUiThread { finish() }
    }.start()
  }
}
`;

const withSmsCaptureFiles = (config) =>
  withDangerousMod(config, [
    'android',
    (c) => {
      const pkg = c.android?.package;
      if (!pkg) throw new Error('withSmsCapture: app config needs `android.package`');
      const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'SmsInbox.kt'), inboxKt(pkg));
      fs.writeFileSync(path.join(dir, 'SmsImportActivity.kt'), importKt(pkg));
      return c;
    },
  ]);

const withSmsCaptureManifest = (config) =>
  withAndroidManifest(config, (c) => {
    const pkg = c.android?.package;
    const manifest = c.modResults.manifest;
    // Exported because Android 14+ delivers implicit intents (Linking.sendIntent) only to exported
    // components; the signature permission keeps every other app out.
    const permission = `${pkg}.permission.IMPORT_SMS`;
    manifest.permission = (manifest.permission ?? []).filter((p) => p.$['android:name'] !== permission);
    manifest.permission.push({ $: { 'android:name': permission, 'android:protectionLevel': 'signature' } });
    AndroidConfig.Permissions.ensurePermission(c.modResults, permission);
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    app.activity = (app.activity ?? []).filter((a) => a.$['android:name'] !== '.SmsImportActivity');
    app.activity.push({
      $: {
        'android:name': '.SmsImportActivity',
        'android:exported': 'true',
        'android:permission': permission,
        'android:excludeFromRecents': 'true',
        'android:noHistory': 'true',
        'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
      },
      'intent-filter': [{ action: [{ $: { 'android:name': `${pkg}.IMPORT_SMS` } }], category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }] }],
    });
    return c;
  });

module.exports = (config) => withSmsCaptureManifest(withSmsCaptureFiles(config));
